# ### Episode overlay
#
# Read `fact_emission_episode` **only if it exists**, and overlay a multi-tag signature when
# an episode is active on the asset. The signature is keyed on `episode.root_cause` and on
# nothing else.
#
# **Why that restriction matters.** The satellite side and the SCADA side have to be
# independent observations of the same hidden ground truth. `04b_Multi_Gas_Cross_Correlation`
# classifies a plume as Fugitive Leak or Incomplete Combustion from the NO2 signature. If
# this notebook generated its telemetry from that classification, then showing the two
# agreeing would be circular — the SCADA layer would be corroborating a conclusion that had
# been written into it. The episode's `root_cause` is upstream of both: it is the physical
# cause, not anybody's inference about it. So `gold_multi_gas_signatures`, the
# `emission_signature` column and every other 04b output are not read here, and must not be.
#
# | root cause | signature |
# |---|---|
# | Seal failure | vibration up, seal gas pressure down |
# | Valve leak | flow imbalance, upstream pressure decline |
# | Tank flashing | vapour pressure up, level drop rate anomalous |
# | Unlit flare | pilot flame drops to 0, stack temperature falls, air-fuel ratio off-spec |
# | Compressor blowby | discharge temperature up, efficiency down, air-fuel ratio off-spec |
# | Corrosion, Pneumatic device | slow pressure decline, valve position drift |
#
# Magnitudes are in units of the tag's **half-band**, so the same number means the same
# thing on a 0.05-0.25 in/s vibration tag and a 800-1200 psig discharge tag. `Corrosion` and
# `Pneumatic device` use a monotonic ramp envelope — a slow decline, which is what those
# failure modes look like; everything else ramps in, holds, and ramps out.

# CELL ********************

