# # 02b — Generate SCADA Telemetry
#
# Writes **`scada_telemetry`**: one row per tag per sample slot, ~17.1M rows for a 30-day
# window across both cadence tiers. This is the only generator in the estate that is large
# enough to matter, so it is **Spark-native throughout** — the telemetry is never pulled
# into pandas, and it is generated and written **one day at a time**.
#
# ### Temporal continuity, and why it is done this way
#
# Consecutive readings must be correlated. A generator that emits independent draws per row
# produces something that is useless for anomaly detection and that anyone who has looked
# at a historian trend recognises as fake on sight. V1's `gen_sensor_telemetry` did exactly
# that — `1.9 + 0.15 * u1 + diurnal` with `u1` hashed per row is white noise around a
# sine — and the lag-1 autocorrelation check below is the one that would have caught it.
#
# The obvious fix — hash noise plus a moving average — is **wrong here**. A moving average
# needs a window ordered by timestamp, so the first `k` rows of any incremental window
# differ from their backfill values unless prior rows are read back. The daily pipeline
# would drift away from the backfill a little more every day.
#
# **Deterministic spectral synthesis** avoids the problem entirely. Each series is the sum
# of six sinusoids at fixed frequencies spanning ~1.6 hours to ~6.5 days, with phases and
# amplitudes hash-derived from `(TOPOLOGY_SEED, series_id, harmonic_index)`. The result is
# smooth, reproducible, and a **pure function of `(series_id, timestamp)`** — no window
# functions, no ordering dependence, no lookback. A single day generated on its own is
# bit-identical to that day inside a 30-day sweep, which is the property the whole
# incremental story rests on.
#
# ### The shared latent load process
#
# One `load(a, s)` series per **asset**, not per tag, generated by the same spectral method
# keyed on `equipment_id`. Every tag on that asset reads from it through its own
# coefficient `beta_t`, signed by measurement type: when a compressor's load rises, suction
# pressure falls while discharge pressure, discharge temperature, RPM and flow all rise. A
# second latent series per **facility** carries ambient and market conditions, so tags
# across a site share a slow common component.
#
# This is the single thing that most distinguishes this table from random values per tag.
# Without it, no cross-tag analytic — no multivariate anomaly detection, no "these four
# tags moved together" — has anything to find.
#
# ### Independence from the satellite side
#
# The episode overlay is keyed on `fact_emission_episode.root_cause` and **never** on
# `emission_signature` from `04b_Multi_Gas_Cross_Correlation`. The satellite side and the
# SCADA side must be independent observations of the same hidden ground truth. If SCADA
# were generated from the NO2 classification, then presenting their agreement as
# corroboration would be circular — the operational data would be "discovering" a
# conclusion that was written into it in the first place. `gold_multi_gas_signatures` and
# every other 04b output is therefore not read here, and the overlay degrades cleanly to a
# no-op when `fact_emission_episode` does not exist.
#
# ### Writes
# `scada_telemetry` only, partitioned by `date_sk`, written day by day with `replaceWhere`
# scoped to one partition per write. No `dim_*` table and no `fact_asset_state` row is
# modified. **Alarm state is not computed here** — that is `02d`, derived from this table.

