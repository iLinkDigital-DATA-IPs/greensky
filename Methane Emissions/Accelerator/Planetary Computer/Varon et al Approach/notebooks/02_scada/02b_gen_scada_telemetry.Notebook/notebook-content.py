# ### Gaps: outages, dropouts and frozen tags
#
# All three are hash-derived from `(TOPOLOGY_SEED, tag_id, index)` and therefore
# reproducible. The construction that matters is the **fixed slot grid**: outage arrivals
# are drawn per tag per 45-day slot anchored at `TELEMETRY_EPOCH`, not per run window. An
# incremental day therefore sees exactly the outages a backfill would have given it, with no
# lookback and no state carried between runs. Looking back one slot is enough because a
# duration is capped at `TELEMETRY_OUTAGE_MAX_H = 120 h`, well inside 45 days.
#
# Outage rows are **absent, not null**. That is the whole point: it is what makes "Sensors
# Offline" computable from `MAX(reading_ts)` rather than from a flag someone has to
# remember to set.

# CELL ********************

OUTAGE_SLOT_S = TELEMETRY_OUTAGE_MEAN_DAYS * 86400.0
FREEZE_SLOT_S = 30 * 86400.0


def _slot_range(slot_s, lo_ts, hi_ts):
    k0 = int(np.floor((lo_ts - TELEMETRY_EPOCH).total_seconds() / slot_s)) - 1
    k1 = int(np.floor((hi_ts - TELEMETRY_EPOCH).total_seconds() / slot_s))
    return range(k0, k1 + 1)


