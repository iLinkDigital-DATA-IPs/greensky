# --- gaps: every gap longer than 2x cadence must be explained -----------------------------------
# Maintenance intervals are listed as an explanation for completeness, but in this model a
# Maintenance reading is present and Substituted, not absent -- so in practice every
# explained gap is an outage. The unexplained remainder is consecutive dropouts, which at
# 0.2% each occur back to back roughly 4e-6 of the time.
GAP_UNEXPLAINED_MAX = 0.001

cad_frame = F.broadcast(spark.createDataFrame(
    live[["tag_sk", "sampling_interval_seconds"]].rename(
        columns={"sampling_interval_seconds": "cad"})))
wg = Window.partitionBy("tag_sk").orderBy("reading_ts")
gaps = (tel.select("tag_sk", "reading_ts")
        .withColumn("prev_t", F.lag("reading_ts").over(wg))
        .filter(F.col("prev_t").isNotNull())
        .join(cad_frame, "tag_sk")
        .withColumn("gap_s", F.unix_timestamp("reading_ts") - F.unix_timestamp("prev_t"))
        .filter(F.col("gap_s") > 2 * F.col("cad")))

maint_dim = F.broadcast(spark.table(STATE_TABLE)
                        .filter("state = 'Maintenance'")
                        .select(F.col("equipment_sk").alias("m_eq"),
                                F.col("start_ts").alias("m_start"),
                                F.coalesce(F.col("end_ts"), F.lit(AS_OF)).alias("m_end")))
eq_frame = F.broadcast(spark.createDataFrame(live[["tag_sk", "equipment_sk"]]))

explained = (gaps
             .join(outage_dim.withColumnRenamed("tag_sk", "o_tag"),
                   (F.col("tag_sk") == F.col("o_tag"))
                   & (F.col("out_start") < F.col("reading_ts"))
                   & (F.col("out_end") > F.col("prev_t")), "left")
             .join(eq_frame, "tag_sk")
             .join(maint_dim,
                   (F.col("equipment_sk") == F.col("m_eq"))
                   & (F.col("m_start") < F.col("reading_ts"))
                   & (F.col("m_end") > F.col("prev_t")), "left")
             .withColumn("explained",
                         F.col("o_tag").isNotNull() | F.col("m_eq").isNotNull()))

# Collapse back to one row per gap before counting. Both joins above are left joins on
# overlap, not containment, so a single long gap can match several Maintenance intervals and
# would otherwise be counted several times. The unexplained rate happens to survive that
# (an unexplained gap matches nothing, so it is never duplicated), but the reported gap
# TOTAL would not, and a number that is only accidentally right is not worth printing.
per_gap = (explained.groupBy("tag_sk", "prev_t", "reading_ts")
           .agg(F.max(F.when(F.col("explained"), 1).otherwise(0)).alias("ok")))
g = per_gap.agg(F.count("*").alias("n"), F.sum("ok").alias("ok")).collect()[0]
n_gaps, n_ok = int(g["n"]), int(g["ok"])
unexplained_rate = (n_gaps - n_ok) / max(ROWS_WRITTEN, 1)
assert unexplained_rate < GAP_UNEXPLAINED_MAX, (
    f"{n_gaps - n_ok:,} of {n_gaps:,} gaps longer than 2x cadence are unexplained by an "
    f"outage or a Maintenance interval ({unexplained_rate:.4%} of rows, cap "
    f"{GAP_UNEXPLAINED_MAX:.2%})"
)
print(f"OK  {n_gaps:,} gaps over 2x cadence, {n_ok:,} explained; unexplained rate "
      f"{unexplained_rate:.5%} (cap {GAP_UNEXPLAINED_MAX:.2%})")

# --- realised rates against target ---------------------------------------------------------------
# Offline share counts the slots a tag could have produced and did not, over every current
# tag: a decommissioned tag is dark for the whole window, and an outage is dark for its own
# duration. Isolated dropouts are deliberately NOT offline -- one missing reading is not a
# dead transmitter, and counting it as one would make the "Sensors Offline" tile meaningless.
#
# ALL_SLOTS is clipped per tag to its install date, so ALL_SLOTS - SLOTS_TOTAL is now exactly
# the decommissioned tags' slots. It used to be WINDOW_DAYS x cadence for every tag, which
# also charged the ~12% of tags installed mid-window for the part of the window that predates
# them -- reading 9.4% offline against a 2% target when the real figure was under 2%.
OFFLINE_REALISED = (ALL_SLOTS - SLOTS_TOTAL + OUTAGE_REMOVED) / ALL_SLOTS
realised = {
    "offline share": (OFFLINE_REALISED, TELEMETRY_OFFLINE_TARGET),
    "bad quality": (int(stats["bad"].sum()) / ROWS_WRITTEN, TELEMETRY_BAD_RATE),
    "dropout": (DROPOUT_REMOVED / max(SLOTS_TOTAL - OUTAGE_REMOVED, 1),
                TELEMETRY_DROPOUT_RATE),
}
print()
print(f"  {'rate':<18}{'realised':>12}{'target':>12}{'band (+/-50%)':>22}")
print("  " + "-" * 64)
off = []
for k, (got, want) in realised.items():
    lo, hi = want * (1 - TELEMETRY_RATE_TOLERANCE), want * (1 + TELEMETRY_RATE_TOLERANCE)
    flag = "" if lo <= got <= hi else "   *"
    if flag:
        off.append((k, got, want))
    print(f"  {k:<18}{got:>12.4%}{want:>12.4%}{f'{lo:.4%} .. {hi:.4%}':>22}{flag}")
assert not off, (
    "realised rate(s) outside 50% of target: "
    + ", ".join(f"{k} {g:.4%} against {w:.4%}" for k, g, w in off)
)
print(f"\nOK  offline, bad-quality and dropout rates all within 50% of target")
print(f"    realised offline share {OFFLINE_REALISED:.3%} "
      f"(design band 1-3%, analytic expectation {OFFLINE_EXPECTED:.3%})")

