# ### Calibration reference, and frozen tags' held values
#
# **Drift** resets at maintenance. `drift_ref_ts` is the end of the most recent
# `Maintenance` interval on the tag's asset at or before the day being generated, falling
# back to a hash-derived last-calibration date inside the past year for assets that have not
# been in for maintenance during the state history. Resolving the reset to the day rather
# than the minute is deliberate: drift is an annual effect, and a few hours of it sits far
# below the noise floor.
#
# **Frozen tags** hold the value they last actually read. That value is produced by running
# the freeze-onset slot through `apply_value_model` — the same function, not a second
# implementation — on a frame of a few rows. Collecting those few rows is not collecting the
# telemetry; it is a control table the size of the frozen-tag count.

