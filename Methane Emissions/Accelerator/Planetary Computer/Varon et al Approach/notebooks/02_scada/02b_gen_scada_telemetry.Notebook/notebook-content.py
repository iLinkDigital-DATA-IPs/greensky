# ---- Spectral synthesis ------------------------------------------------------------------
# (period in hours, amplitude weight). Fixed frequencies; only phase and amplitude are
# hash-derived. Periods are deliberately incommensurate and none is close to 2x the 900s
# standard cadence -- a harmonic near the Nyquist period aliases into what looks like white
# noise and eats the autocorrelation margin. The shortest here is 1.63 h = 6.5 standard
# slots, giving cos(2*pi*dt/P) = 0.57 for that component and >0.93 for every other one.
