# ### Joining `fact_asset_state`
#
# A reading is conditioned on the state its asset was in at that instant, which is a range
# join on `equipment_sk` and the interval containing `reading_ts`. Done naively that is a
# broadcast nested loop: 570k readings a day against 20k intervals is 1.1e10 comparisons.
#
# Instead each interval is exploded into the **hour buckets** it covers and the join becomes
# an equi-join on `(equipment_sk, hour_bucket)` with the range predicate applied afterwards
# to the handful of candidates in each bucket. Intervals are at least 15 minutes long, so no
# bucket holds more than a few.
#
# ### The predicate is half-open, and has to be
#
# `start_ts <= reading_ts AND reading_ts < end_ts`, never `BETWEEN start_ts AND end_ts`.
#
# `02a` guarantees intervals **tile** — one interval's `end_ts` is exactly the next one's
# `start_ts`, and it asserts that difference is zero. A closed predicate on both ends
# therefore matches *both* intervals for any reading landing exactly on a boundary, and the
# join stops being one-to-one. At ~177 boundaries an asset-day, with cadences of 300s and
# 900s dividing the hour, a boundary landing exactly on a slot is not rare. The half-open
# convention is what makes the join exactly one-to-one, and it is the reason the state
# machine can tile without ambiguity in the first place.
#
# The open interval per asset carries a **null** `end_ts`, so it is coalesced to a far-future
# `eff_end` before the comparison rather than tested separately — a null on the right of `<`
# would make the predicate null, not true, and every reading in the open interval would be
# dropped.
#
# The same convention is used for every other interval join in this notebook: outages,
# freezes and episodes. Each is half-open, and each source is de-overlapped before the join
# so no reading can match two of them either.
#
# `02a` asserts that intervals tile continuously with no gaps and no overlaps, so exactly
# one state row matches every reading. That is asserted here too rather than assumed — a
# silent duplicate would inflate the row count and break the `(tag_sk, reading_ts)`
# uniqueness check much further downstream.

# CELL ********************

HOUR_S = 3600

# Only instrumented assets can produce a reading, so the other ~2,470 assets' intervals are
# dropped before anything is exploded.
INSTRUMENTED_SKS = sorted(int(e) for e in live["equipment_sk"].unique())

state_all = (spark.table(STATE_TABLE)
             .select("equipment_sk", "state", "start_ts", "end_ts")
             .filter(F.col("equipment_sk").isin(INSTRUMENTED_SKS))
             .withColumn("eff_end", F.coalesce(F.col("end_ts"),
                                               F.lit(AS_OF + pd.Timedelta(days=3650))))
             .drop("end_ts"))


def _ramp_phi():
    span = F.unix_timestamp("eff_end") - F.unix_timestamp("start_ts")
    phi = F.when(span > 0,
                 (F.unix_timestamp("reading_ts") - F.unix_timestamp("start_ts"))
                 / span.cast("double")).otherwise(F.lit(0.0))
    return F.least(F.greatest(phi, F.lit(0.0)), F.lit(1.0))


def state_buckets(lo_ts, hi_ts):
    """Intervals overlapping [lo, hi), exploded to the hour buckets inside that range.

    Both ends are clamped to the range. Clamping the LOW end is what keeps this bounded: a
    Running interval that opened three weeks ago and is still open would otherwise explode
    into 500 buckets, and there is one such interval per asset. The range predicate in
    attach_state still decides membership, so clamping loses nothing.
    """
    lo_u = int(pd.Timestamp(lo_ts).timestamp())
    hi_u = int(pd.Timestamp(hi_ts).timestamp())
    sub = state_all.filter(
        (F.col("start_ts") < F.lit(hi_ts)) & (F.col("eff_end") > F.lit(lo_ts)))
    lo_b = F.floor(F.greatest(F.unix_timestamp("start_ts"), F.lit(lo_u)) / F.lit(HOUR_S))
    hi_b = F.floor(F.least(F.unix_timestamp("eff_end"), F.lit(hi_u)) / F.lit(HOUR_S))
    return (sub
            .withColumn("hour_bucket", F.explode(F.sequence(lo_b, hi_b)))
            .select("equipment_sk", "state", "start_ts", "eff_end", "hour_bucket"))


def attach_state(df, buckets):
    """One state row per reading, plus the ramp fraction for Startup/Shutdown."""
    j = (df.withColumn("hour_bucket", F.floor(F.unix_timestamp("reading_ts") / F.lit(HOUR_S)))
           .join(F.broadcast(buckets), ["equipment_sk", "hour_bucket"], "inner")
           .filter((F.col("reading_ts") >= F.col("start_ts"))
                   & (F.col("reading_ts") < F.col("eff_end"))))
    return (j.withColumn("ramp_phi", _ramp_phi())
             .drop("hour_bucket", "start_ts", "eff_end"))


def attach_state_direct(df):
    """Range join with no bucketing, for frames of a few rows.

    The frozen-tag frame has one row per frozen tag and its onsets are scattered across the
    whole window, so bucketing would explode the state table over 30 days to resolve a
    dozen readings. A broadcast nested loop over a dozen rows is the cheaper shape.
    """
    s = state_all.select(F.col("equipment_sk").alias("s_eq"), "state", "start_ts", "eff_end")
    j = (F.broadcast(df).join(
            s,
            (F.col("equipment_sk") == F.col("s_eq"))
            & (F.col("reading_ts") >= F.col("start_ts"))
            & (F.col("reading_ts") < F.col("eff_end")), "inner")
         .drop("s_eq"))
    return j.withColumn("ramp_phi", _ramp_phi()).drop("start_ts", "eff_end")


