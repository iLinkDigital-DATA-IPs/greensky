# --- cross-tag correlation on the same asset ---------------------------------------------------
# The requirement is at least one pair with |corr| > 0.5. In practice most pairs on a
# compressor clear it, because beta_t puts 50-60% of each tag's variance in the shared load.
CROSS_MIN = 0.50
multi = (live.groupby("equipment_sk")["tag_sk"].count().sort_values(ascending=False))
probe_assets = [int(e) for e in multi[multi >= 4].index[:6]]
assert probe_assets, "no asset carries four or more tags -- cannot test cross-tag structure"

pairs_found, best = [], []
for eq in probe_assets:
    sks = [int(t) for t in live[live["equipment_sk"] == eq]["tag_sk"]]
    sub = (tel.filter(F.col("tag_sk").isin(sks)).filter("quality_code = 'Good'")
              .select("tag_sk", "reading_ts", "value_num"))
    a = sub.alias("a")
    b = sub.alias("b")
    cor = (a.join(b, (F.col("a.reading_ts") == F.col("b.reading_ts"))
                  & (F.col("a.tag_sk") < F.col("b.tag_sk")))
            .groupBy(F.col("a.tag_sk").alias("t1"), F.col("b.tag_sk").alias("t2"))
            .agg(F.corr("a.value_num", "b.value_num").alias("r"), F.count("*").alias("n"))
            .filter(F.col("n") >= F.lit(MIN_PAIRS)).toPandas())
    if len(cor):
        cor["absr"] = cor["r"].abs()
        pairs_found.append(int((cor["absr"] > CROSS_MIN).sum()))
        best.append(cor.sort_values("absr", ascending=False).head(3))

allbest = pd.concat(best) if best else pd.DataFrame()
name_of = live.set_index("tag_sk")["tag_name"].to_dict()
assert sum(pairs_found) >= 1, (
    "no tag pair on any probed asset reaches |corr| > 0.5. The shared latent load series is "
    "not reaching the tags -- check LOAD_BETA and LATENT_W_LOAD."
)
print(f"OK  {sum(pairs_found)} tag pair(s) on {len(probe_assets)} probed asset(s) exceed "
      f"|corr| {CROSS_MIN}")
for r in allbest.sort_values("absr", ascending=False).head(8).itertuples():
    print(f"    {name_of.get(int(r.t1), r.t1):<22}{name_of.get(int(r.t2), r.t2):<22}"
          f"{r.r:+.3f}")

