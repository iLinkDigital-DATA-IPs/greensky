# ### The value model as a Spark expression
#
# `apply_value_model` is applied to every generated day and, unchanged, to the three-row
# frame that resolves frozen tags' held values. Writing it once as a function is what keeps
# a frozen tag's held value on the same model as every other reading, instead of a second
# implementation that quietly drifts from the first.

# CELL ********************

def apply_value_model(df):
    """Everything from the spectral latents through to the quantised value."""
    t_sec = (F.col("interval_index") * F.col("sampling_interval_seconds")).cast("double")
    doy = F.dayofyear("reading_ts") + F.hour("reading_ts") / F.lit(24.0)
    hod = F.hour("reading_ts") + F.minute("reading_ts") / F.lit(60.0)

    df = (df
          .withColumn("t_sec", t_sec)
          .withColumn("idio", spectral_expr("tg", F.col("t_sec")))
          .withColumn("load", spectral_expr("ld", F.col("t_sec")))
          .withColumn("site", spectral_expr("fc", F.col("t_sec")))
          .withColumn("seas", F.col("seas_amp")
                      * F.cos(2 * np.pi * (doy - F.lit(PROCESS_SEASONAL_PEAK_DOY)) / F.lit(365.25)))
          .withColumn("diur", F.col("diur_amp")
                      * F.cos(2 * np.pi * (hod - F.lit(PROCESS_DIURNAL_PEAK_HOUR)) / F.lit(24.0)))
          .withColumn("ambient",
                      F.lit(AMBIENT_MEAN_F)
                      + F.lit(AMBIENT_SEASONAL_F)
                      * F.cos(2 * np.pi * (doy - F.lit(AMBIENT_PEAK_DOY)) / F.lit(365.25))
                      + F.lit(AMBIENT_DIURNAL_F)
                      * F.cos(2 * np.pi * (hod - F.lit(AMBIENT_PEAK_HOUR)) / F.lit(24.0))
                      + F.lit(AMBIENT_LATENT_F) * F.col("site")))

    # --- state anchor, residual scale and ambient blend, with the ramp states interpolating
    ss = F.col("ramp_phi") * F.col("ramp_phi") * (F.lit(3.0) - F.lit(2.0) * F.col("ramp_phi"))
    w = F.when(F.col("state") == "Startup", ss).otherwise(F.lit(1.0) - ss)

    def pick(run_c, sby_c, dwn_c):
        return (F.when(F.col("state") == "Running", F.col(run_c))
                 .when(F.col("state") == "Standby", F.col(sby_c))
                 .when(F.col("state").isin("Down", "Maintenance"), F.col(dwn_c))
                 .otherwise((F.lit(1.0) - w) * F.col(dwn_c) + w * F.col(run_c)))

    df = (df
          .withColumn("anchor_frac", pick("anch_run", "anch_sby", "anch_dwn"))
          .withColumn("resid", pick("resid_run", "resid_sby", "resid_dwn"))
          .withColumn("amb_w", pick("amb_run", "amb_sby", "amb_dwn")))

    base_plain = F.col("anchor_frac") * F.col("centre") * (F.lit(1.0) + F.col("seas") + F.col("diur"))
    df = df.withColumn(
        "base",
        F.when(F.col("is_temperature"),
               (F.lit(1.0) - F.col("amb_w")) * base_plain + F.col("amb_w") * F.col("ambient"))
         .otherwise(base_plain))

    # --- the three latent series, mixed to a total sd of sigma_proc whatever beta is
    mix = ((F.lit(LATENT_W_IDIO) * F.col("idio")
            + F.lit(LATENT_W_LOAD) * F.col("beta") * F.col("load")
            + F.lit(LATENT_W_FAC) * F.col("gamma") * F.col("site"))
           / F.col("latent_norm"))

    # --- per-row hash: noise, and the quality/dropout draws used later
    h = row_hash_col(F.col("tag_id"), F.col("interval_index"))
    df = df.withColumn("rh", h)
    u0, u1 = hash_uniform(F.col("rh"), 0), hash_uniform(F.col("rh"), 1)
    z = F.sqrt(F.lit(-2.0) * F.log(u0)) * F.cos(F.lit(2.0 * np.pi) * u1)

    drift_years = F.least(
        F.greatest((F.unix_timestamp("reading_ts") - F.unix_timestamp("drift_ref_ts"))
                   / F.lit(365.25 * 86400.0), F.lit(0.0)),
        F.lit(DRIFT_MAX_YEARS))
    noise_scale = F.greatest(F.lit(STATE_NOISE_FLOOR), F.col("resid"))

    df = (df
          .withColumn("v_raw",
                      F.col("base")
                      + F.col("resid") * F.col("sigma_proc") * mix
                      + F.col("resid") * F.col("drift_sign") * F.col("drift_per_year") * drift_years
                      + noise_scale * F.col("noise_sigma") * z)
          .withColumn("v_raw", F.col("v_raw") + F.col("ep_delta"))
          .withColumn("v_raw", F.coalesce(F.col("ep_abs"), F.col("v_raw"))))

    # --- clip to the plausible envelope, then quantise to the instrument's resolution
    lo = F.least(F.col("base"), F.col("env_lo_base")) - F.lit(ENVELOPE_PAD) * F.col("band")
    hi = F.greatest(F.col("base"), F.col("env_hi_base")) + F.lit(ENVELOPE_PAD) * F.col("band")
    lo = (F.when(F.col("is_non_negative"), F.greatest(lo, F.lit(0.0)))
           .when(F.col("is_pressure"), F.greatest(lo, F.lit(PRESSURE_FLOOR_PSIG)))
           .otherwise(lo))
    v = F.least(F.greatest(F.col("v_raw"), lo), hi)
    return df.withColumn(
        "value_model",
        F.round(F.round(v / F.col("resolution")) * F.col("resolution"), 6))


