def attach_episodes(df, lo_ts, hi_ts):
    """Per-reading episode delta, in the tag's own units. A no-op when no episode table."""
    zero = (df.withColumn("ep_delta", F.lit(0.0))
              .withColumn("ep_abs", F.lit(None).cast("double"))
              .withColumn("is_episode", F.lit(False)))
    if not EPISODES_AVAILABLE:
        return zero

    ep = (spark.table(EPISODE_TABLE)
          .select("equipment_sk", "root_cause", "start_ts", "end_ts")
          .filter((F.col("start_ts") < F.lit(hi_ts)) & (F.col("end_ts") > F.lit(lo_ts)))
          .join(episode_sig, "root_cause", "inner"))
    if ep.rdd.isEmpty():
        return zero

    prog = ((F.unix_timestamp("reading_ts") - F.unix_timestamp("ep_start"))
            / F.greatest(F.unix_timestamp("ep_end") - F.unix_timestamp("ep_start"),
                         F.lit(1)).cast("double"))
    prog = F.least(F.greatest(prog, F.lit(0.0)), F.lit(1.0))
    # smoothstep in, hold, smoothstep out -- or a monotonic ramp for the slow-decline causes
    up = F.least(prog / F.lit(EPISODE_ONSET_FRACTION), F.lit(1.0))
    dn = F.least((F.lit(1.0) - prog) / F.lit(EPISODE_ONSET_FRACTION), F.lit(1.0))
    plateau = F.least(up, dn)
    env_raw = F.when(F.col("ep_ramp"), prog).otherwise(plateau)
    env = env_raw * env_raw * (F.lit(3.0) - F.lit(2.0) * env_raw)

    hits = (df.select("tag_sk", "reading_ts", "equipment_sk", "tag_name", "half_band")
              .join(F.broadcast(ep.withColumnRenamed("start_ts", "ep_start")
                                  .withColumnRenamed("end_ts", "ep_end")),
                    ["equipment_sk", "tag_name"], "inner")
              .filter((F.col("reading_ts") >= F.col("ep_start"))
                      & (F.col("reading_ts") < F.col("ep_end")))
              .withColumn("env", env)
              .groupBy("tag_sk", "reading_ts")
              .agg(F.sum(F.when(F.col("ep_mode") == "band",
                                F.col("env") * F.col("ep_mag") * F.col("half_band"))
                          .otherwise(F.lit(0.0))).alias("ep_delta"),
                   F.max(F.when((F.col("ep_mode") == "abs") & (F.col("env") >= F.lit(0.5)),
                                F.col("ep_mag"))).alias("ep_abs")))

    return (df.join(hits, ["tag_sk", "reading_ts"], "left")
              .withColumn("is_episode", F.col("ep_delta").isNotNull())
              .withColumn("ep_delta", F.coalesce(F.col("ep_delta"), F.lit(0.0))))

