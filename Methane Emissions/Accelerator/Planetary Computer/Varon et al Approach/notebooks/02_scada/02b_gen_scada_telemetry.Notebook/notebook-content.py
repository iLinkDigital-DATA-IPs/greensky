TELEMETRY_SCHEMA = ["tag_sk", "tag_id", "equipment_sk", "area_sk", "facility_sk",
                    "reading_ts", "date_sk", "value_num", "uom", "quality_code",
                    "operating_state", "is_interpolated", "is_synthetic", "ingest_ts"]




def slots_for_day(day_ts):
    """Slots a day should produce before any gap is applied, computed from the dimension.

    Asserted against the post-join row count below, which checks the install-date filter and
    the fact_asset_state join in one go: if the state table had an overlap the join would
    duplicate a reading and the two numbers would part company.
    """
    day_end = day_ts + pd.Timedelta(days=1)
    n = 0
    for cad, grp in live.groupby("sampling_interval_seconds"):
        cad, per_day = int(cad), 86400 // int(cad)
        inst = grp["install_date"]
        n += int((inst <= day_ts).sum()) * per_day
        last = int(day_end.timestamp()) // cad
        for d in inst[(inst > day_ts) & (inst < day_end)]:
            first = int(np.ceil((d - _EPOCH_TS).total_seconds() / cad))
            n += max(0, last - first)
    return n


def build_day(day_ts):
    """Every reading for one day, across every cadence tier."""
    day_end = day_ts + pd.Timedelta(days=1)
    buckets = state_buckets(day_ts, day_end)
    drift_ref = spark.createDataFrame(drift_ref_frame(day_ts))

    parts = []
    for cad in CADENCES:
        base_idx = int(pd.Timestamp(day_ts).timestamp()) // cad
        n_slots = 86400 // cad
        slots = (spark.range(0, n_slots)
                 .withColumn("interval_index", F.col("id") + F.lit(base_idx))
                 .drop("id"))
        tags = tag_dim.filter(F.col("sampling_interval_seconds") == F.lit(cad))
        parts.append(tags.crossJoin(F.broadcast(slots)))

    df = parts[0]
    for p in parts[1:]:
        df = df.unionByName(p)

    df = (df
          .withColumn("reading_ts", F.timestamp_seconds(
              F.col("interval_index") * F.col("sampling_interval_seconds")))
          .filter(F.col("reading_ts") >= F.col("install_date"))
          .join(load_dim, "equipment_id", "inner")
          .join(site_dim, "facility_id", "inner")
          .join(F.broadcast(drift_ref), "tag_sk", "left")
          .withColumn("drift_ref_ts",
                      F.coalesce(F.col("drift_ref_ts"), F.col("cal_anchor_ts"))))

    df = attach_state(df, buckets)
    df = attach_episodes(df, day_ts, day_end)
    df = apply_value_model(df)

    # --- gaps ------------------------------------------------------------------------------
    # Outages and dropouts are FLAGGED here and filtered at the write, so the run can count
    # exactly how many rows each removed. Counting them by differencing row counts would
    # need a second pass over the day.
    df = (df.join(outage_dim.withColumnRenamed("tag_sk", "o_tag"),
                  (F.col("tag_sk") == F.col("o_tag"))
                  & (F.col("reading_ts") >= F.col("out_start"))
                  & (F.col("reading_ts") < F.col("out_end")), "left")
            .withColumn("is_outage", F.col("o_tag").isNotNull())
            .drop("o_tag", "out_start", "out_end"))
    df = df.withColumn("is_dropout",
                       ~F.col("is_outage")
                       & (hash_uniform(F.col("rh"), 2) < F.lit(TELEMETRY_DROPOUT_RATE)))
    df = df.withColumn("keep", ~F.col("is_outage") & ~F.col("is_dropout"))

    # --- frozen hold ---------------------------------------------------------------------------
    df = (df.join(freeze_dim.withColumnRenamed("tag_sk", "f_tag"),
                  (F.col("tag_sk") == F.col("f_tag"))
                  & (F.col("reading_ts") >= F.col("frz_start"))
                  & (F.col("reading_ts") < F.col("frz_end")), "left")
            .withColumn("is_frozen", F.col("frz_hold").isNotNull()))

    # --- quality -------------------------------------------------------------------------------
    u_bad, u_unc, u_side = (hash_uniform(F.col("rh"), 3), hash_uniform(F.col("rh"), 4),
                            hash_uniform(F.col("rh"), 5))
    quality = (F.when(F.col("state") == "Maintenance", F.lit("Substituted"))
                .when(u_bad < F.lit(TELEMETRY_BAD_RATE), F.lit("Bad"))
                .when(F.col("is_frozen") | F.col("state").isin(*RAMP_STATES), F.lit("Uncertain"))
                .when(u_unc < F.lit(TELEMETRY_UNCERTAIN_RATE), F.lit("Uncertain"))
                .otherwise(F.lit("Good")))
    rail = (F.when(u_side < F.lit(0.5), F.col("normal_min") - F.col("rail_span"))
             .otherwise(F.col("normal_max") + F.col("rail_span")))

    df = (df
          .withColumn("quality_code", quality)
          .withColumn("value_num",
                      F.when(F.col("quality_code") == "Bad",
                             F.round(F.round(rail / F.col("resolution")) * F.col("resolution"), 6))
                       .when(F.col("is_frozen"), F.col("frz_hold"))
                       .otherwise(F.col("value_model")))
          .withColumn("is_interpolated",
                      (F.col("state") == "Maintenance") | F.col("is_frozen"))
          .withColumn("operating_state", F.col("state"))
          .withColumn("date_sk", F.date_format("reading_ts", "yyyyMMdd").cast("long"))
          .withColumn("is_synthetic", F.lit(True))
          .withColumn("ingest_ts", F.current_timestamp()))
    return df


