# ### State conditioning — the change that makes traces look real
#
# A `Down` compressor reading zero flow and ambient temperature, rather than noise around
# its normal band. Each `(state, measurement_type)` pair gives two numbers:
#
# - an **anchor**, as a fraction of the tag's normal centre, that the reading settles on
# - a **residual scale**, the fraction of the Running process swing that survives
#
# | state | flow / rpm | pressure | temperature | vibration | level | pilot |
# |---|---|---|---|---|---|---|
# | Running | normal band | normal band | normal band | normal band | normal band | 1 |
# | Standby | ~0 (2% / 0%), swing 5% / 2% | relaxes to **line pressure**, swing 25% | 65% of the way to **ambient**, swing 25% | 4%, swing 5% | holds, swing 40% | 1 |
# | Down | **0**, swing 0% | **static**, swing 10% | **ambient**, swing 5% | 0, swing 2% | holds, swing 15% | **0** |
# | Maintenance | as Down | as Down | as Down | as Down | as Down | 0, and `quality_code = 'Substituted'` |
# | Startup / Shutdown | smoothstep **ramp** between the Down profile and Running across the interval — never a step |
#
# "Line pressure" is not one number. A compressor's *suction* pressure **rises** toward the
# upstream line when nothing is drawing on it, while its *discharge* pressure **falls**
# toward that same line. Keying only on `measurement_type` would move both the same way and
# get the physics backwards, so pressure anchors are additionally keyed on the tag's role:
#
# | role | at rest (Standby) | static (Down) | tags |
# |---|---|---|---|
# | suction | 1.25 x centre | 1.35 x centre | `suction_pressure` |
# | discharge | 0.45 | 0.25 | `discharge_pressure` |
# | seal | 0.30 | 0.05 | `seal_gas_pressure` |
# | line | 1.05 | 1.08 | `inlet_pressure`, `pressure` |
# | differential | 0.00 | 0.00 | `differential_pressure` (no flow, no dp) |
# | vapour | 1.00 | 1.00 | `vapour_pressure` (a tank's vapour space does not care) |
#
# Two details that matter. **Instrument noise does not vanish when the machine stops**, but
# a flow meter below its turndown pins at zero rather than showing full-scale noise, so
# noise is scaled by the residual with a floor of `STATE_NOISE_FLOOR = 0.15` — a Down
# compressor then reads ~2 mscfd on a 1500-4500 band, which reads as zero on a trend.
# **Calibration drift is a span error on a live measurement**, so it scales with the
# residual and no floor: a zeroed meter shows no span drift.
#
# One accepted simplification: `air_fuel_ratio` goes to 0 in Down, which is right for a
# stopped compressor engine and wrong for a flare whose pilot is still lit. The contract is
# `state_multiplier(state, measurement_type)` and flares stop rarely, so it is left keyed on
# measurement type and noted here rather than special-cased.

