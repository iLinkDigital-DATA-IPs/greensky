# --- lag-1 autocorrelation, on a deterministic sample of 50 tags --------------------------------
# pilot_flame is excluded: it is a binary lit/not-lit tag, so a flare that never stopped
# gives a constant series whose autocorrelation is undefined rather than low. Frozen tags
# are excluded for the same reason -- their flat stretch is deliberate.
AUTOCORR_TAGS = 50
AUTOCORR_MIN = 0.70
# Minimum consecutive pairs before a tag's correlation is trusted. It has to scale with the
# window: a one-day incremental run gives a standard tag 96 readings, so a fixed floor of
# 200 would silently drop every tag and leave the check measuring nothing. The estimate
# itself is fine at this size -- sampling error on r ~ 0.95 with 48 pairs is a few percent,
# nowhere near the 0.70 threshold.
MIN_PAIRS = max(40, min(200, (86400 // STANDARD_INTERVAL_SECONDS) * WINDOW_DAYS // 2))

frozen_sks = set(int(t) for t in freeze_dim_pdf["tag_sk"]) if len(freeze_dim_pdf) else set()
cand = live[(live["measurement_type"] != "pilot_flame") & (~live["tag_sk"].isin(frozen_sks))]
cand = cand.sort_values("tag_id", kind="mergesort")
pick = cand.iloc[:: max(1, len(cand) // AUTOCORR_TAGS)].head(AUTOCORR_TAGS)
pick_sks = [int(t) for t in pick["tag_sk"]]
cad_of = {int(r.tag_sk): int(r.sampling_interval_seconds) for r in pick.itertuples()}

w = Window.partitionBy("tag_sk").orderBy("reading_ts")
sample = (tel.filter(F.col("tag_sk").isin(pick_sks))
          .filter("quality_code = 'Good'")
          .select("tag_sk", "reading_ts", "value_num")
          .withColumn("prev_v", F.lag("value_num").over(w))
          .withColumn("prev_t", F.lag("reading_ts").over(w))
          .withColumn("gap_s", F.unix_timestamp("reading_ts") - F.unix_timestamp("prev_t"))
          .join(F.broadcast(spark.createDataFrame(
              pd.DataFrame({"tag_sk": pick_sks,
                            "cad": [cad_of[s] for s in pick_sks]}))), "tag_sk")
          .filter(F.col("gap_s") == F.col("cad")))

# A tag whose asset was stopped for the whole window reads a constant, and corr() on a
# constant is null rather than low. Those are dropped rather than counted as failures -- but
# the coverage assertion below is what stops that becoming a way for the check to pass by
# measuring nothing.
ac = (sample.groupBy("tag_sk")
      .agg(F.corr("value_num", "prev_v").alias("r1"), F.count("*").alias("n"))
      .filter((F.col("n") >= F.lit(MIN_PAIRS)) & F.col("r1").isNotNull()).toPandas())

assert len(ac) >= AUTOCORR_TAGS * 0.8, (
    f"only {len(ac)} of {AUTOCORR_TAGS} sampled tags had enough consecutive Good pairs with "
    f"a defined correlation (needed {MIN_PAIRS} pairs each) to measure autocorrelation"
)
worst = ac.sort_values("r1").head(5)
