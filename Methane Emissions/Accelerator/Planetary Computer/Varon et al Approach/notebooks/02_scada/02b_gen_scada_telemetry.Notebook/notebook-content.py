# ### The value model
#
# For tag `t` on asset `a` at time `s`:
#
# ```
# value = base(t) x state_multiplier(state(a,s), measurement_type)
#              x (1 + seasonal(s) + diurnal(s))
#       + beta_t x load(a,s)      shared per-asset latent process factor
#       + gamma_t x site(f,s)     shared per-facility ambient / market factor
#       + idio_t(s)               the tag's own spectral wander
#       + drift(t,s)              calibration drift, from drift_per_year
#       + noise(t,s)              from noise_sigma
# ```
#
# then clipped to a plausible envelope and quantised to `resolution`.
#
# The three latent terms are mixed so the **total** process deviation has standard
# deviation `PROCESS_SD_FRACTION x half_band` whatever `beta_t` is — `beta_t` sets how much
# of a tag's variance is shared with its neighbours, not how large its swing is. At
# `|beta| ~ 0.9` roughly 60% of a tag's variance comes from the asset's load series, which
# is what produces cross-tag correlations of 0.6-0.9 on the same machine.
#
# `PROCESS_SD_FRACTION = 0.25` puts the normal band edge at 4 sigma, so a healthy tag sits
# inside `[normal_min, normal_max]` essentially always and the excursions that do happen
# mean something.

